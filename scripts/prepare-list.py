items = []
for i, line in enumerate(raw.splitlines(), 1):
  body = re.sub(r'^(?:\d+|об)\.\s*', '', line).strip()
  quote = re.search('["«“]', body)
  if quote:
    author = body[:quote.start()].strip(' .,:')
    tail = body[quote.start()+1:]
    end = re.search('["»]', tail)
    title = tail[:end.start()] if end else tail
  else:
    author, title = '', body
  aliases = []
  if i in corrections: author, title, aliases = corrections[i]
  if i in architecture: author, title, aliases = architecture[i]
  author = re.sub(r'\s+', ' ', author or '')
  if 'ван Гог' in author: author_aliases = ['Ван Гог', 'Винсент ван Гог']
  elif 'да Винчи' in author: author_aliases = ['Леонардо', 'Леонардо да Винчи', 'Да Винчи']
  elif 'Эль Греко' in author: author_aliases = ['Эль Греко']
  elif i == 5: author_aliases = ['Агесандр Полидор Афинодор', 'Агесандр и Полидор и Афинодор']
  elif i == 170: author_aliases = ['Кибальников и Бембель', 'Александр Кибальников и Андрей Бембель']
  else: author_aliases = []
  if author in full_names: author_aliases.append(full_names[author])
  # Portraits may be recalled without initials; the full original remains visible.
  no_initials = re.sub(r'(?<![А-Яа-яA-Za-z])[А-ЯA-Z]\.\s*', '', title)
  if no_initials != title: aliases.append(no_initials)
  item = dict(id=i, author=author, title=title.strip(), authorAliases=author_aliases, titleAliases=list(dict.fromkeys(aliases)), authorRequired=bool(author), note='', original=line)
  matching = next((p for p in (root/'public/paintings').glob(f'{i}.*') if p.suffix.lower() in ['.jpg', '.jpeg', '.png', '.webp']), None)
  item['image'] = f'paintings/{matching.name}' if matching else None
  items.append(item)
assert len(items) == 170
(root/'src/lib/collection.json').write_text(json.dumps(items, ensure_ascii=False, indent=2)+'\n')
print(f'Подписей: {len(items)}. Изображений: {sum(bool(i["image"]) for i in items)}')
